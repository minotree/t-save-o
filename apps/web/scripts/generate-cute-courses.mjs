// Authoring-time layout search. The app only consumes the saved static data.
import { createServer } from 'vite';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const server=await createServer({root,server:{middlewareMode:true},appType:'custom'});
try {
  const {composeCoursePuzzle,normalRows,hardRows}=await server.ssrLoadModule('/src/game/course-content.ts');
  const {reverseArrow}=await server.ssrLoadModule('/src/game/reverse-arrow.ts');
  const {findHeadBlocker,headTip,pointTouchesShape}=await server.ssrLoadModule('/src/game/engine.ts');
  const {readableHead}=await server.ssrLoadModule('/src/game/pen-stroke.ts');
  let seed=20261029;
  const random=()=>{seed=(Math.imul(seed,1664525)+1013904223)>>>0;return seed/4294967296;};
  function usable(arrow){
    const h=readableHead(arrow),m=Math.hypot(h.direction.x,h.direction.y),u={x:h.direction.x/m,y:h.direction.y/m};
    return [headTip({...arrow,head:h}),h.anchor,
      {x:h.anchor.x-u.y*h.width/2,y:h.anchor.y+u.x*h.width/2},
      {x:h.anchor.x+u.y*h.width/2,y:h.anchor.y-u.x*h.width/2}].every(p=>pointTouchesShape(p,arrow.shape));
  }
  const labels=new Set();
  function author(sourceRows,id){
    const rows=[...sourceRows];
    const longest=rows.length>1?4:Math.max(...rows.map(row=>row.length));
    for(let attempt=0;attempt<400;attempt++){
      if(attempt){
        for(let i=rows.length-1;i>0;i--){const j=Math.floor(random()*(i+1));[rows[i],rows[j]]=[rows[j],rows[i]];}
      }
      if(labels.has(rows.join('/')))continue;
      const offsets=rows.map(row=>Math.round(22+(longest-row.length)*294*(attempt?random():.5)));
      const layout={id,rows,offsets,lineHeight:330+(attempt%4)*24,flipped:[]};
      const puzzle=composeCoursePuzzle(layout);
      const variants=new Map(puzzle.arrows.map(a=>[a.id,[a,reverseArrow(a)].filter(v=>usable(v)&&!findHeadBlocker(v,[v],puzzle))]));
      if([...variants.values()].some(v=>!v.length))continue;
      const pending=[...puzzle.arrows];
      while(pending.length){
        const index=pending.findIndex(a=>variants.get(a.id).some(v=>!findHeadBlocker(v,pending,puzzle)));
        if(index<0)break;
        const a=pending[index],chosen=variants.get(a.id).find(v=>!findHeadBlocker(v,pending,puzzle));
        if(chosen!==a)layout.flipped.push(a.id);
        pending.splice(index,1);
      }
      if(!pending.length){labels.add(rows.join('/'));console.log(id,rows.join(' / '),'strokes',puzzle.arrows.length,'reversed',layout.flipped.length);return {...layout,rows:[...rows]};}
    }
    throw new Error(`Cannot author solvable board: ${id} ${rows.join('/')}`);
  }
  const normal=normalRows.map((rows,i)=>author(rows,`normal-${i+1}`));
  const hard=hardRows.map((rows,i)=>author(rows,`hard-${i+1}`));
  await writeFile(new URL('../src/game/course-layouts.generated.ts',import.meta.url),
    '// Generated by scripts/generate-cute-courses.mjs; no runtime generation.\n'+
    'export const normalLayouts = '+JSON.stringify(normal,null,2)+' as const;\n'+
    'export const hardLayouts = '+JSON.stringify(hard,null,2)+' as const;\n');
} finally {await server.close();}
